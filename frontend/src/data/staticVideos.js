// Cache helper functions
export const getCachedVideos = (sector) => {
    try {
        const cacheKey = `course_videos_${sector}`;
        const cached = localStorage.getItem(cacheKey);

        if (cached) {
            const { data, timestamp } = JSON.parse(cached);
            const age = Date.now() - timestamp;
            const maxAge = 24 * 60 * 60 * 1000; // 24 hours

            if (age < maxAge) {
                console.log(`✅ Using cached videos for ${sector} (age: ${Math.round(age / 1000 / 60)} mins)`);
                return data;
            }
        }
    } catch (e) {
        console.error('Cache read error:', e);
    }
    return null;
};

export const setCachedVideos = (sector, videos) => {
    try {
        const cacheKey = `course_videos_${sector}`;
        const cacheData = {
            data: videos,
            timestamp: Date.now()
        };
        localStorage.setItem(cacheKey, JSON.stringify(cacheData));
        console.log(`✅ Cached ${videos.length} videos for ${sector}`);
    } catch (e) {
        console.error('Cache write error:', e);
    }
};
