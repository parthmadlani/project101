// Get all resources for a sector
export function getResourcesForSector(sector) {
  const resources = CURATED_RESOURCES[sector] || CURATED_RESOURCES.healthcare;
  
  // Flatten all resources into a single array
  const allResources = [];
  for (const skill in resources) {
    allResources.push(...resources[skill]);
  }
  
  return allResources;
}

// Get resources for a specific skill
export function getResourcesForSkill(sector, skill) {
  const sectorData = CURATED_RESOURCES[sector] || CURATED_RESOURCES.healthcare;
  return sectorData[skill] || [];
}

// Search resources
export function searchResources(sector, query) {
  const resources = getResourcesForSector(sector);
  const lowerQuery = query.toLowerCase();
  
  return resources.filter(r => 
    r.title.toLowerCase().includes(lowerQuery) ||
    r.description.toLowerCase().includes(lowerQuery) ||
    r.channel.toLowerCase().includes(lowerQuery)
  );
}

